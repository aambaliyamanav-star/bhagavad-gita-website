function findCuratedAnswer(query) {
  const q = String(query).toLowerCase();
  for (const topic of CURATED_GITA_TOPICS) {
    if (topic.keywords.some((kw) => q.includes(kw))) {
      return topic.answer;
    }
  }
  return null;
}

