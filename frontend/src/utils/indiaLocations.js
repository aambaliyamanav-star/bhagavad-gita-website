/**
 * Multi-lingual fuzzy/prefix search:
 * Matches input text against Gujarati, Hindi, and English names of the item.
 * E.g. typing 'gu' in English matches 'ગુજરાત' when website is in Gujarati!
 */
export const searchLocationItems = (items, query, language = "gu") => {
  if (!query || !query.trim()) return items;
  const q = query.trim().toLowerCase();

  return items.filter((item) => {
    // Always keep OTHER option visible
    if (item.id === "OTHER") return true;

    const en = (item.nameEn || item.id || "").toLowerCase();
    const gu = (item.nameGu || "").toLowerCase();
    const hi = (item.nameHi || "").toLowerCase();
    const cur = (item.name || "").toLowerCase();

    return (
      en.includes(q) ||
      gu.includes(q) ||
      hi.includes(q) ||
      cur.includes(q)
    );
  });
};
