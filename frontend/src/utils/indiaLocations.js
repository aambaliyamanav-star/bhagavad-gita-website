// Helper function to get cities list for selected state and language
// Cities are sorted alphabetically A to Z (a b c d પ્રમાણે) with "OTHER" at top
export const getCitiesForState = (stateId, language = "gu") => {
  const otherLabel = language === "en" ? "Other" : language === "hi" ? "अन्य" : "અન્ય";
  const defaultList = [
    { id: "OTHER", name: otherLabel },
  ];

  if (!stateId || stateId === "OTHER") {
    return defaultList;
  }

  let list = [];
  if (stateId === "Gujarat") {
    list = GUJARAT_CITIES;
  } else if (OTHER_STATE_CITIES[stateId]) {
    list = OTHER_STATE_CITIES[stateId];
  } else {
    return defaultList;
  }

  // Pre-sorted in A to Z order
  const mapped = list.map((item) => ({
    id: item.id,
    name: language === "en" ? item.nameEn : language === "hi" ? item.nameHi : item.nameGu,
  }));

  // First option is always "OTHER" so user can select it to type custom city/village
  return [
    { id: "OTHER", name: otherLabel },
    ...mapped,
  ];
};

// Helper function to get localized state list
// States are sorted alphabetically A to Z (a b c d પ્રમાણે) with "OTHER" at top
export const getLocalizedStates = (language = "gu") => {
  const otherLabel = language === "en" ? "Other" : language === "hi" ? "अन्य" : "અન્ય";
  const statesWithoutOther = INDIAN_STATES.filter((st) => st.id !== "OTHER");

  const mapped = statesWithoutOther.map((st) => ({
    id: st.id,
    name: language === "en" ? st.nameEn : language === "hi" ? st.nameHi : st.nameGu,
  }));

  return [
    { id: "OTHER", name: otherLabel },
    ...mapped,
  ];
};
